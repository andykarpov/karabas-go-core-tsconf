#!/usr/bin/env python3
"""
gen_cen.py: z80_silicon_cen.v from the files of z80-silicon-rtl (github.com/dr-Titus/z80-silicon-rtl,
GPL v3, rtl/Z80.v, Registers.v, Register_selector.v, kept here as they are).

The core runs on both edges of the clock of the Z80 (43 blocks on the falling edge, 13 on the rising
one). Here it runs on one fast clock with two enables, as T80pa (CEN_p / CEN_n):
  always @ (posedge clk)  ->  always @ (posedge clk) if (cen_p)
  always @ (negedge clk)  ->  always @ (posedge clk) if (cen_n)
every module with `input clk` gets `input cen_p, input cen_n` and every `.clk(clk)` the two enables;
every reg without an initial value gets 0 (the FPGA's INIT, and 4-state simulators do not stay at X);
the modules are renamed z80s_<name> (Decoder, Registers, ... are names other sources may use; the top
Z80 is z80s_Z80). cen_p and cen_n must never be 1 at once and must alternate (the rising and the falling
edge of the clock of the Z80).

Usage: python3 gen_cen.py   (in this directory; writes z80_silicon_cen.v)
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCES = ["Registers.v", "Register_selector.v", "Z80.v"]
OUT = HERE / "z80_silicon_cen.v"


def init_regs(t):
    """Every reg without an initial value gets 0 in an initial block before the endmodule of its module:
    the value of the FPGA (INIT 0), and a 4-state simulator (iverilog, ISim) does not stay at X."""
    out, n = [], 0
    for part in re.split(r"(?<=\bendmodule\b)", t):
        code = re.sub(r"//[^\n]*", "", part)
        names = []
        # body declarations (up to ";") and output reg ports (up to "," or ")")
        for m in re.finditer(r"\boutput\s+reg\b\s*(\[[^\]]*\])?\s*(\w+)\s*(=)?", code):
            if not m.group(3):
                names.append(m.group(2))
        for m in re.finditer(r"^\s*reg\b\s*(\[[^\]]*\])?([^;]*);", code, re.M):
            for d in m.group(2).split(","):
                d = d.strip()
                if d and "=" not in d and "[" not in d:
                    names.append(d)
        # those an initial block of the core sets already (Registers.v: its test values)
        done = set()
        for m in re.finditer(r"\binitial\b(.*?)\bend\b", code, re.S):
            done.update(re.findall(r"(\w+)\s*=", m.group(1)))
        names = [x for x in names if x not in done]
        if names and "endmodule" in part:
            init = "    initial begin%s end\n" % "".join(" %s = 0;" % x for x in names)
            k = part.rfind("endmodule")
            part = part[:k] + init + part[k:]
            n += len(names)
        out.append(part)
    return "".join(out), n


def main():
    text = {f: (HERE / f).read_text(encoding="utf-8") for f in SOURCES}
    names = []
    for t in text.values():
        names += re.findall(r"^\s*module\s+(\w+)\s*\(", t, re.M)
    if len(names) != len(set(names)):
        sys.exit("gen_cen: a module name twice")
    counts = {"pos": 0, "neg": 0, "port": 0, "inst": 0, "init": 0}
    out = []
    for f in SOURCES:
        t = text[f]
        t, n = re.subn(r"always\s*@\s*\(\s*posedge\s+clk\s*\)", "always @ (posedge clk) if (cen_p)", t)
        counts["pos"] += n
        t, n = re.subn(r"always\s*@\s*\(\s*negedge\s+clk\s*\)", "always @ (posedge clk) if (cen_n)", t)
        counts["neg"] += n
        t, n = re.subn(r"\binput(\s+)clk\s*,", r"input\1clk, input cen_p, input cen_n,", t)
        counts["port"] += n
        t, n = re.subn(r"\.clk\s*\(\s*clk\s*\)", ".clk(clk), .cen_p(cen_p), .cen_n(cen_n)", t)
        counts["inst"] += n
        # module declarations and instances: <Name> <instance> (
        t = re.sub(r"^(\s*module\s+)(\w+)", lambda m: m.group(1) + "z80s_" + m.group(2), t, flags=re.M)
        t = re.sub(r"^(\s*)(%s)(\s+\w+\s*\()" % "|".join(map(re.escape, names)),
                   lambda m: m.group(1) + "z80s_" + m.group(2) + m.group(3), t, flags=re.M)
        # every clk now goes with an enable: anything else is a use the conversion does not know
        bad = [l for l in t.splitlines() if re.search(r"\bclk\b", l.split("//")[0])
               and not re.search(r"posedge clk\) if \(cen_[pn]\)|input\s+clk, input cen_p|\.clk\(clk\), \.cen_p", l)]
        if bad or re.search(r"negedge", t):
            sys.exit("gen_cen: %s: a clk left: %s" % (f, (bad or ["negedge"])[0].strip()))
        t, n = init_regs(t)
        counts["init"] += n
        out.append("// ---- %s\n%s\n" % (f, t))
    insts = len(re.findall(r"^\s*z80s_\w+\s+\w+\s*\(", "".join(out), re.M))
    head = ("// Generated by gen_cen.py from %s of z80-silicon-rtl (GPL v3): one clock, the enables\n"
            "// cen_p (the rising edge of the Z80 clock) and cen_n (the falling one). Do not edit.\n"
            "// (`default_nettype wire: the ports of the core are plain input / output; a file before it in a\n"
            "// prj may have left `default_nettype none)\n"
            "// %d rising, %d falling blocks, %d modules with clk, %d instances with clk, %d modules.\n\n"
            % (", ".join(SOURCES), counts["pos"], counts["neg"], counts["port"], counts["inst"], len(names)))
    OUT.write_text(head + "`default_nettype wire\n\n" + "".join(out), encoding="utf-8")
    print("gen_cen: %d rising, %d falling, %d ports, %d clk instances, %d modules, %d instances, %d registers set to 0"
          % (counts["pos"], counts["neg"], counts["port"], counts["inst"], len(names), insts, counts["init"]))


if __name__ == "__main__":
    main()
