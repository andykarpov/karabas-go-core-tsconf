#!/bin/bash
# The FM part of the OPL4 (opl3_fpga, SystemVerilog) as one Verilog-2001 file for XST:
# sv2v, then $clog2 (XST 14.7 does not take it in parameters and port widths) as a macro.
# Run after a change of the .sv files and commit opl3_fm_gen.v with them.
set -e
cd "$(dirname "$0")"
SV2V=${SV2V:-sv2v}
OUT=../opl3_fm_gen.v
{
	echo '// generated by rtl/sound/opl4/opl3/gen_v.sh from the .sv files of opl3/ (sv2v); do not edit'
	echo '`define CLOG2(x) ((x)<=1?0:(x)<=2?1:(x)<=4?2:(x)<=8?3:(x)<=16?4:(x)<=32?5:(x)<=64?6:(x)<=128?7:(x)<=256?8:(x)<=512?9:(x)<=1024?10:(x)<=2048?11:(x)<=4096?12:(x)<=8192?13:(x)<=16384?14:(x)<=32768?15:16)'
	"$SV2V" opl3_pkg.sv $(ls *.sv | grep -v '^opl3_pkg.sv$') | sed 's/\$clog2(/`CLOG2(/g'
} > "$OUT"
echo "$OUT: $(grep -c '^module' "$OUT") modules"
