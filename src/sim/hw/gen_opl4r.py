#!/usr/bin/env python3
"""gen_opl4r.py ROM: the expected sums of opl4r.asm (the YRW801 ROM read back on the board): per block of
64 KB a Fletcher sum in 16 bits, s1 += byte, s2 += s1 (s2 kept; depends on the order of the bytes).
Writes opl4r_data.asm next to it."""
import sys
from pathlib import Path

rom = Path(sys.argv[1]).read_bytes()
assert len(rom) == 0x200000, len(rom)
sums = []
for blk in range(32):
    s1 = s2 = 0
    for b in rom[blk * 0x10000:(blk + 1) * 0x10000]:
        s1 = (s1 + b) & 0xFFFF
        s2 = (s2 + s1) & 0xFFFF
    sums.append(s2)
text = "; generated by gen_opl4r.py\nexpect:\n" + "".join(
    "\tdw " + ",".join("#%04X" % v for v in sums[i:i + 8]) + "\n" for i in range(0, 32, 8))
Path(__file__).with_name("opl4r_data.asm").write_text(text)
print(" ".join("%04X" % v for v in sums))
