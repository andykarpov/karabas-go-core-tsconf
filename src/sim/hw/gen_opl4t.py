#!/usr/bin/env python3
"""gen_opl4t.py: the data of opl4t.asm (a hardware test of the OPL4 sample memory and formats): a sine of
256 samples at -6 dBFS in the three formats of the OPL4 (8-bit, 12-bit packed as ymfm / openMSX read it,
16-bit big endian), the three wave headers (tones 384..386 in RAM at #200000), and an 8x8 font of 0-9 A-F.
Writes opl4t_data.asm next to it."""
import math
from pathlib import Path

N = 256
s16 = [int(round(16384 * math.sin(2 * math.pi * i / N))) for i in range(N)]
s12 = [v >> 4 for v in s16]          # 12-bit values (the top 12 bits)
s8 = [v >> 8 for v in s16]

b8 = [v & 0xFF for v in s8]
b16 = []
for v in s16:
    b16 += [(v >> 8) & 0xFF, v & 0xFF]
b12 = []
for i in range(0, N, 2):
    a, b = s12[i] & 0xFFF, s12[i + 1] & 0xFFF
    # even sample: byte0 = a[11:4], low nibble of byte1 = a[3:0]; odd: byte2 = b[11:4], high nibble of byte1 = b[3:0]
    b12 += [a >> 4, ((b & 0xF) << 4) | (a & 0xF), b >> 4]

def header(fmt, addr):
    end = (0x10000 - N) & 0xFFFF     # the end, negated: N samples
    return [(fmt << 6) | (addr >> 16), (addr >> 8) & 0xFF, addr & 0xFF,
            0x00, 0x00,               # loop start: sample 0
            end >> 8, end & 0xFF,
            0x00,                     # LFO / VIB
            0xF0,                     # AR 15, D1R 0
            0x00,                     # DL 0, D2R 0
            0x0F,                     # RC 0, RR 15
            0x00]                     # AM
hdr = header(0, 0x201000) + header(1, 0x202000) + header(2, 0x203000)

# 8x8 glyphs of 0-9 A-F (rows top to bottom, 5 pixels wide in bits 6..2)
G = {
    '0': ["01110", "10001", "10011", "10101", "11001", "10001", "01110"],
    '1': ["00100", "01100", "00100", "00100", "00100", "00100", "01110"],
    '2': ["01110", "10001", "00001", "00110", "01000", "10000", "11111"],
    '3': ["11110", "00001", "00001", "01110", "00001", "00001", "11110"],
    '4': ["00010", "00110", "01010", "10010", "11111", "00010", "00010"],
    '5': ["11111", "10000", "11110", "00001", "00001", "10001", "01110"],
    '6': ["00110", "01000", "10000", "11110", "10001", "10001", "01110"],
    '7': ["11111", "00001", "00010", "00100", "01000", "01000", "01000"],
    '8': ["01110", "10001", "10001", "01110", "10001", "10001", "01110"],
    '9': ["01110", "10001", "10001", "01111", "00001", "00010", "01100"],
    'A': ["01110", "10001", "10001", "11111", "10001", "10001", "10001"],
    'B': ["11110", "10001", "10001", "11110", "10001", "10001", "11110"],
    'C': ["01110", "10001", "10000", "10000", "10000", "10001", "01110"],
    'D': ["11110", "10001", "10001", "10001", "10001", "10001", "11110"],
    'E': ["11111", "10000", "10000", "11110", "10000", "10000", "11111"],
    'F': ["11111", "10000", "10000", "11110", "10000", "10000", "10000"],
}
font = []
for c in "0123456789ABCDEF":
    font += [int(r, 2) << 2 for r in G[c]] + [0]

def db(name, data):
    out = [name + ":"]
    for i in range(0, len(data), 16):
        out.append("\tdb " + ",".join("#%02X" % x for x in data[i:i + 16]))
    return "\n".join(out) + "\n"

text = "; generated by gen_opl4t.py\n" + db("sin8", b8) + db("sin12", b12) + db("sin16", b16) + db("hdrs", hdr) + db("font", font)
Path(__file__).with_name("opl4t_data.asm").write_text(text)
print("opl4t_data.asm: %d + %d + %d bytes of samples, %d of headers" % (len(b8), len(b12), len(b16), len(hdr)))
